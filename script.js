// ================= VARIABLES =================

const container =
    document.getElementById("certificateContainer");

const searchInput =
    document.getElementById("searchInput");

const totalCertificates =
    document.getElementById("totalCertificates");

const noResult =
    document.getElementById("noResult");

const filters =
    document.querySelectorAll(".filter");


// ================= TOTAL =================

totalCertificates.textContent =
    certificates.length + "+";


// ================= DISPLAY =================

function displayCertificates(data) {

    container.innerHTML = "";

    if (data.length === 0) {

        noResult.style.display = "block";

        return;
    }

    noResult.style.display = "none";


    data.forEach((certificate, index) => {

        const card = document.createElement("div");

        card.className = "certificate-card";


        card.innerHTML = `

            <img
                src="${certificate.image}"
                class="certificate-image"
                alt="${certificate.title}"
            >

            <div class="card-body">

                <h3>
                    ${certificate.title}
                </h3>

                <p class="issuer">
                    <i class="fa-solid fa-user"></i>
                    ${certificate.issuer}
                </p>

                <p class="date">
                    <i class="fa-solid fa-calendar"></i>
                    ${certificate.date}
                </p>

                <span class="category">
                    ${certificate.category}
                </span>

                <div class="card-buttons">

                    <button
                        class="view-btn"
                        onclick='openCertificate(${JSON.stringify(certificate)})'
                    >
                        <i class="fa-solid fa-eye"></i>
                        View Certificate
                    </button>

                    <a
                        href="${certificate.file}"
                        class="download-btn"
                        target="_blank"
                    >
                        <i class="fa-solid fa-download"></i>
                        Download Certificate
                    </a>

                </div>

            </div>
        `;


        container.appendChild(card);

    });

}


// ================= INITIAL DISPLAY =================

displayCertificates(certificates);


// ================= SEARCH =================

searchInput.addEventListener("input", function () {

    const searchValue =
        this.value.toLowerCase().trim();


    const filtered =
        certificates.filter(certificate =>

            certificate.title
                .toLowerCase()
                .includes(searchValue)

            ||

            certificate.issuer
                .toLowerCase()
                .includes(searchValue)

            ||

            certificate.category
                .toLowerCase()
                .includes(searchValue)

        );


    displayCertificates(filtered);

});


// ================= CATEGORY FILTER =================

filters.forEach(button => {

    button.addEventListener("click", function () {

        filters.forEach(btn =>
            btn.classList.remove("active")
        );

        this.classList.add("active");


        const category =
            this.dataset.category;


        if (category === "All") {

            displayCertificates(certificates);

            return;
        }


        const filtered =
            certificates.filter(
                certificate =>
                    certificate.category === category
            );


        displayCertificates(filtered);

    });

});


